/**
 * This used to be a grid and the grid is what failed. It drew one character per tile under a
 * two-row vertical-digit header, and on session 01a09887 the model got 14 of 27 tile claims
 * right, every error the same one-column shift, after spending a third of its output budget
 * on column arithmetic and then refusing to call the tool again.
 *
 * So the property these tests exist to hold is no longer "the header and the body agree". It
 * is that A TILE AT A NAMED COORDINATE IS RECOVERABLE FROM THE OUTPUT WITHOUT COUNTING
 * ANYTHING, and `parseRows` below is the whole of it: it turns the rows back into tiles by
 * reading numbers, refuses a row whose runs are not contiguous from `area.fromX` to
 * `area.toX`, and the fixtures then compare every tile of the window against a map the test
 * planted rather than against anything the renderer computed. A run boundary that moves by
 * one, a run dropped, a kind that changes, a row that loses its y - each of those fails on
 * the tile it touches and names it.
 *
 * The fixtures plant ground tile by tile and hold their own expectation, so the check is
 * against the park the test built and not against a second copy of the renderer's precedence
 * rules. A table regenerated by the same reasoning that produced a bug agrees with the bug.
 */

function withGame(build: (game: FakeGame) => void, run: (game: FakeGame) => void, size = 40): void {
    const game = new FakeGame(size, size);
    build(game);
    const restore = game.install();

    try {
        run(game);
    } finally {
        restore();
    }
}

function drawn(outcome: MapViewOutcome): MapViewSuccess {
    assert.equal(outcome.ok, true, outcome.ok ? "" : outcome.error);
    return outcome as MapViewSuccess;
}

/** `<firstX>-<lastX><kind>`, both ends always, kind never starting with a digit. */
const RUN = /^(\d+)-(\d+)([^\s\d][^\s]*)$/;

/**
 * Every tile of the window, keyed "x,y", read back out of the rows.
 *
 * Nothing here counts a position: a tile's x comes from the numbers written beside it, and a
 * row's y from the label the row carries. The contiguity assertions are the other half - a
 * format that lets a tile fall between two runs, or into two of them, would let the renderer
 * lose a tile silently, which is the failure the grid's header was there to prevent.
 */
function parseRows(view: MapViewSuccess): Record<string, string> {
    const tiles: Record<string, string> = {};
    const rows = view.rows.filter(function (row) { return row.indexOf("cut:") !== 0; });

    assert.equal(rows.length, view.area.toY - view.area.fromY + 1,
        "one line per y of `area` and no others");

    for (let i = 0; i < rows.length; i++) {
        const head = /^y(\d+): /.exec(rows[i]);

        assert.ok(head, "a row has to name its own y: " + JSON.stringify(rows[i]));

        const y = Number((head as RegExpExecArray)[1]);

        assert.equal(y, view.area.fromY + i,
            "rows run in ascending y from area.fromY: " + JSON.stringify(rows[i]));

        const parts = rows[i].substring((head as RegExpExecArray)[0].length).split(" ");
        let next = view.area.fromX;

        for (let p = 0; p < parts.length; p++) {
            const run = RUN.exec(parts[p]);

            assert.ok(run, "a run has to read `<firstX>-<lastX><kind>`: "
                + JSON.stringify(parts[p]) + " in " + JSON.stringify(rows[i]));

            const from = Number((run as RegExpExecArray)[1]);
            const to = Number((run as RegExpExecArray)[2]);
            const kind = (run as RegExpExecArray)[3];

            assert.ok(to >= from, "a run cannot end before it starts: " + parts[p]);
            assert.equal(from, next, "run " + parts[p] + " on " + JSON.stringify(rows[i])
                + " starts at " + String(from) + " and the run before it ended at "
                + String(next - 1) + "; a gap or an overlap here is a tile the reader cannot place");

            for (let x = from; x <= to; x++) {
                tiles[String(x) + "," + String(y)] = kind;
            }

            next = to + 1;
        }

        assert.equal(next, view.area.toX + 1, "the last run of " + JSON.stringify(rows[i])
            + " ends at " + String(next - 1) + " and area.toX is " + String(view.area.toX));
    }

    return tiles;
}

/** The kind the rows give for one tile, with no counting and no formula. */
function kindAt(view: MapViewSuccess, x: number, y: number): string {
    const tiles = parseRows(view);
    const key = String(x) + "," + String(y);

    assert.ok(Object.prototype.hasOwnProperty.call(tiles, key),
        "the rows do not cover " + key + " at all");

    return tiles[key];
}

function countOf(view: MapViewSuccess, kind: string): number {
    const tiles = parseRows(view);
    let found = 0;

    for (const key in tiles) {
        if (tiles[key] === kind) {
            found++;
        }
    }

    return found;
}

/** A ride the fake will report, without going through ridecreate. */
function addRide(game: FakeGame, id: number): void {
    game.rides.push({
        id: id, name: "Ride " + String(id), type: 0, status: "closed", price: [0],
        stations: [{ start: null, entrance: null, exit: null, length: 0, queueTime: 0 }],
        excitement: -1, intensity: 0, nausea: 0, totalCustomers: 0, totalProfit: 0,
        downtime: 0, reliability: 100, flags: 0, value: null
    });
}

function addTrack(game: FakeGame, x: number, y: number, ride: number): void {
    game.tile(x, y).elements.push({ type: "track", baseZ: 96, ride: ride, trackType: 0, direction: 0 });
}

function addWater(game: FakeGame, x: number, y: number): void {
    Object.assign(game.tile(x, y).elements[0], { waterHeight: 112 });
}

