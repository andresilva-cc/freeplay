test("a queue and a footpath on the same tile are different kinds", function () {
    withGame(function (game) {
        game.addPath(9, 9, true);
    }, function (game) {
        const asQueue = drawn(renderMapView({ left: 5, top: 5, right: 14, bottom: 14 }));
        assert.equal(kindAt(asQueue, 9, 9), "Q");

        game.tile(9, 9).elements = game.tile(9, 9).elements.filter(function (element) {
            return element.type !== "footpath";
        });
        game.addPath(9, 9);

        const asPath = drawn(renderMapView({ left: 5, top: 5, right: 14, bottom: 14 }));
        assert.equal(kindAt(asPath, 9, 9), "P",
            "the same tile with an ordinary path on it has to read differently from a queue");
    });
});

test("no kind is a prefix of a coordinate, so a run cannot be read two ways", function () {
    // The kinds and the spans share one line, so a kind beginning with a digit or carrying a
    // hyphen would make `12-14r3` ambiguous. This is generated from what actually rendered.
    withGame(plantedPark, function () {
        const view = drawn(renderMapView({ left: 5, top: 5, right: 34, bottom: 34 }));
        const tiles = parseRows(view);
        const seen: Record<string, boolean> = {};

        for (const key in tiles) {
            seen[tiles[key]] = true;
        }

        const kinds = Object.keys(seen);

        assert.ok(kinds.length >= 14, "this window is supposed to hold nearly every kind, and holds "
            + String(kinds.length));

        for (let i = 0; i < kinds.length; i++) {
            assert.doesNotMatch(kinds[i], /^\d/, "a kind starting with a digit runs into the span: " + kinds[i]);
            assert.doesNotMatch(kinds[i], /[-\s]/, "a kind carrying a hyphen or a space splits the run: " + kinds[i]);
        }
    });
});

